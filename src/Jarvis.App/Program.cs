// Program.cs: the entry point of the Jarvis desktop app (top-level statements, so there is no Main method).
// What happens from double-clicking "Start Jarvis.cmd" to a ready window:
//   1. The .cmd file makes sure the local .NET SDK exists, builds Jarvis.App in Release mode, then launches Jarvis.App.exe.
//   2. This file runs: sets up WinForms and installs crash handlers that write to data/startup-error.log.
//   3. AppBootstrapper.CreateAsync (AppBootstrapper.cs) loads jarvis.settings.json, starts the local speech
//      (Whisper) server in the background, makes sure the local language model server is answering (Jarvis's own
//      llama-server if installed, otherwise LM Studio) and sends it a tiny warm-up request, then builds the
//      assistant, speaker and voice runtime and returns them bundled as a JarvisDesktopContext.
//   4. Application.Run opens JarvisMainForm (the JarvisMainForm.*.cs files) and blocks until the window closes.
// If any startup step throws, the error is logged and shown in a message box instead of the window opening.
using Jarvis.App;
using Jarvis.Core;
using System.Text;

// Standard WinForms setup (high-DPI, visual styles, default font) generated by the project template.
ApplicationConfiguration.Initialize();

// Cancelled when the app shuts down; passed into startup so long waits can be abandoned.
using var cancellationTokenSource = new CancellationTokenSource();

// Last-resort logging for exceptions on background threads that nobody caught.
AppDomain.CurrentDomain.UnhandledException += (_, eventArgs) =>
{
    if (eventArgs.ExceptionObject is Exception exception)
    {
        StartupCrashLog.Write(exception);
    }
};

// Same, for exceptions thrown on the UI thread (for example inside an event handler).
Application.ThreadException += (_, eventArgs) =>
{
    if (eventArgs.Exception is not null)
    {
        StartupCrashLog.Write(eventArgs.Exception);
    }
};

// Startup is awaited here, before any window exists, so the user sees nothing until the model server is ready.
try
{
    var context = await AppBootstrapper.CreateAsync(cancellationTokenSource.Token);
    Application.Run(new JarvisMainForm(context));
}
catch (Exception exception)
{
    StartupCrashLog.Write(exception);
    MessageBox.Show(
        exception.Message,
        "Jarvis Startup Failed",
        MessageBoxButtons.OK,
        MessageBoxIcon.Error);
}

// Appends startup failures to data/startup-error.log so a crash before the window opens leaves a trace.
static class StartupCrashLog
{
    public static void Write(Exception exception)
    {
        try
        {
            var logPath = JarvisDataPaths.Resolve("data/startup-error.log");
            Directory.CreateDirectory(Path.GetDirectoryName(logPath)!);
            var builder = new StringBuilder();
            builder.Append('[')
                .Append(DateTimeOffset.Now.ToString("yyyy-MM-dd HH:mm:ss zzz"))
                .AppendLine("]");
            builder.AppendLine(exception.ToString());
            builder.AppendLine();
            File.AppendAllText(logPath, builder.ToString());
        }
        catch
        {
            // Best effort only.
        }
    }
}
